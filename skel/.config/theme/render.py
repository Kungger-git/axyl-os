# -------------------------------------------------------------------- cava ---
def write_cava(p: dict) -> None:
    path = CONFIG / "cava/config"
    if not path.exists():
        return
    lines = path.read_text().splitlines()

    out, skipping = [], False
    for line in lines:
        stripped = line.strip()
        if stripped == CAVA_BEGIN:
            skipping = True
            continue
        if stripped == CAVA_END:
            skipping = False
            continue
        if not skipping:
            out.append(line)

    try:
        start = next(i for i, l in enumerate(out) if l.strip() == "[color]")
    except StopIteration:
        return

    end = len(out)
    for i in range(start + 1, len(out)):
        s = out[i].strip()
        if s.startswith("[") and s.endswith("]"):
            end = i
            break

    managed = re.compile(r"^\s*(foreground|background|gradient|gradient_count|gradient_color_\d+)\s*=")
    keep = [l for i, l in enumerate(out) if not (start < i < end and managed.match(l))]

    block = [
        CAVA_BEGIN,
        'foreground = "%s"' % p["accent"],
        'background = "%s"' % p["bg"],
        "gradient = 1",
        "gradient_count = 3",
        'gradient_color_1 = "%s"' % p["accent"],
        'gradient_color_2 = "%s"' % p["accent_alt"],
        'gradient_color_3 = "%s"' % p["cyan"],
        CAVA_END,
    ]
    idx = next(i for i, l in enumerate(keep) if l.strip() == "[color]")
    head = keep[: idx + 1]
    tail = keep[idx + 1:]
    while head and not head[-1].strip():
        head.pop()
    while tail and not tail[0].strip():
        tail.pop(0)
    path.write_text("\n".join(head + [""] + block + [""] + tail) + "\n")


# ---------------------------------------------------------------- KDE / Qt ---
def rgb(value: str) -> str:
    """KDE/.colors want decimal R,G,B triples."""
    return ",".join(str(c) for c in hex_to_rgb(value))


def kde_color_sections(p: dict) -> list[str]:
    """The [Colors:*] groups shared by kdeglobals and a .colors scheme file."""

    def section(name: str, bg: str, bg_alt: str, fg: str) -> list[str]:
        return [
            "[Colors:%s]" % name,
            "BackgroundAlternate=%s" % rgb(bg_alt),
            "BackgroundNormal=%s" % rgb(bg),
            "DecorationFocus=%s" % rgb(p["accent"]),
            "DecorationHover=%s" % rgb(p["accent"]),
            "ForegroundActive=%s" % rgb(p["accent"]),
            "ForegroundInactive=%s" % rgb(p["fg_muted"]),
            "ForegroundLink=%s" % rgb(p["secondary"]),
            "ForegroundNegative=%s" % rgb(p["red"]),
            "ForegroundNeutral=%s" % rgb(p["yellow"]),
            "ForegroundNormal=%s" % rgb(fg),
            "ForegroundPositive=%s" % rgb(p["green"]),
            "ForegroundVisited=%s" % rgb(p["accent_alt"]),
            "",
        ]

    lines: list[str] = []
    lines += section("Window", p["bg_panel"], p["bg"], p["fg"])
    lines += section("View", p["bg"], p["bg_panel"], p["fg"])
    lines += section("Button", p["bg_elem"], p["bg_panel"], p["fg"])
    lines += section("Selection", p["accent"], p["accent"], p["bg"])
    lines += section("Tooltip", p["bg_elem"], p["bg_elem"], p["fg"])
    lines += section("Complementary", p["bg_panel"], p["bg"], p["fg"])
    lines += section("Header", p["bg_panel"], p["bg"], p["fg"])
    return lines


