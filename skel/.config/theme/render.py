# KColorSchemeManager (Dolphin and other KF6 apps) reads [UiSettings] ColorScheme
# and, when it is empty, force-applies Breeze Light based on
# QStyleHints::colorScheme(). That light palette overrides the platform theme and
# leaves dark text on Kvantum's dark background. Pointing it at our scheme keeps
# the dark palette. The value is the scheme id (~/.local/share/color-schemes/<id>.colors).
KDE_UISETTINGS = """
[UiSettings]
ColorScheme=opencode
"""


def write_kde(p: dict) -> None:
    body = KDE_HEADER % (rgb(p["fg_muted"]), rgb(p["fg_muted"]))
    body += "\n" + "\n".join(kde_color_sections(p)).rstrip() + "\n"
    # kdeglobals drives KF6 apps (Dolphin); the .colors file makes the scheme
    # selectable in System Settings.
    write(CONFIG / "kdeglobals", body + KDE_UISETTINGS)
    write(Path.home() / ".local/share/color-schemes/opencode.colors", body)


# qt6ct stores its palette as one flat list of #AARRGGBB colours, in this order.
QT6CT_ROLES = [
    "WindowText", "Button", "Light", "Midlight", "Dark", "Mid", "Text",
    "BrightText", "ButtonText", "Base", "Window", "Shadow", "Highlight",
    "HighlightedText", "Link", "LinkVisited", "AlternateBase", "ToolTipBase",
    "ToolTipText", "PlaceholderText", "Accent",
]


def qt6ct_colors(p: dict) -> list[str]:
    roles = {
        "WindowText": p["fg"],
        "Button": p["bg_elem"],
        "Light": p["overlay"],
        "Midlight": p["border"],
        "Dark": p["bg"],
        "Mid": p["bg_panel"],
        "Text": p["fg"],
        "BrightText": p["bright"]["white"],
        "ButtonText": p["fg"],
        "Base": p["bg"],
        "Window": p["bg_panel"],
        "Shadow": p["overlay"],
        "Highlight": p["accent"],
        "HighlightedText": p["bg"],
        "Link": p["secondary"],
        "LinkVisited": p["accent_alt"],
        "AlternateBase": p["bg_panel"],
        "ToolTipBase": p["bg_elem"],
        "ToolTipText": p["fg"],
        "PlaceholderText": p["fg_muted"],
        "Accent": p["accent"],
    }
    return ["#ff" + roles[r].lstrip("#") for r in QT6CT_ROLES]


QT6CT_SCHEME = """# GENERATED by ~/.config/theme/render.py -- do not edit by hand.
# Source of truth: ~/.config/theme/palette.json

[ColorScheme]
active_colors=%s
disabled_colors=%s
inactive_colors=%s
"""


def write_qt6ct(p: dict) -> None:
    active = qt6ct_colors(p)
    disabled = list(active)
    for role in ("WindowText", "Text", "ButtonText", "BrightText"):
        disabled[QT6CT_ROLES.index(role)] = "#ff" + p["fg_muted"].lstrip("#")
    write(
        CONFIG / "qt6ct/colors/opencode.conf",
        QT6CT_SCHEME % (", ".join(active), ", ".join(disabled), ", ".join(active)),
    )


