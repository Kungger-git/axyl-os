def hex_to_rgb(value: str) -> tuple[int, int, int]:
    value = value.lstrip("#")
    return tuple(int(value[i:i + 2], 16) for i in (0, 2, 4))


def rgba(value: str, alpha: float) -> str:
    r, g, b = hex_to_rgb(value)
    return f"rgba({r}, {g}, {b}, {alpha:g})"


def build_tokens(p: dict, layout: dict | None = None) -> dict:
    layout = layout if layout is not None else layout_of(p)
    t = {k: v for k, v in p.items() if isinstance(v, str)}
    for key, value in list(t.items()):
        t["nh_" + key] = value.lstrip("#")  # no-hash form for rgba(...) colour types
    t["bg_rgba"] = rgba(p["bg"], 0.92)
    t["bg_panel_rgba"] = rgba(p["bg_panel"], 0.95)
    t["accent_rgba"] = rgba(p["accent"], 0.55)
    for k, v in p["bright"].items():
        t[f"b_{k}"] = v
        t[f"nh_b_{k}"] = v.lstrip("#")
    for k, v in layout.items():
        t["lay_" + k] = str(v).lower() if isinstance(v, bool) else str(v)
    t["rofi_elem_radius"] = max(int(layout["rofi_radius"]) - 6, 2)
    t["rofi_radius"] = str(layout["rofi_radius"])
    t["rofi_width"] = str(layout["rofi_width"])
    return t


def fill(text: str, tokens: dict) -> str:
    for key, value in tokens.items():
        text = text.replace("{{%s}}" % key, str(value))
    return text


def write(path: Path, body: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(body if body.endswith("\n") else body + "\n")


# ---------------------------------------------------------------- Hyprland ---
def write_hypr_palette(p: dict) -> None:
    lines = [
        "-- GENERATED by ~/.config/theme/render.py -- do not edit by hand.",
        "-- Source of truth: ~/.config/theme/palette.json",
        "return {",
    ]
    for key in ORDER:
        lines.append('  %-10s = "%s",' % (key, p[key].lstrip("#")))
    lines.append("}")
    write(CONFIG / "hypr/conf/palette.lua", "\n".join(lines))


